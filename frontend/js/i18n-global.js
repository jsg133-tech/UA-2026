export function t(key) {
  const lang = getCurrentLanguage();
  const pageKey = getPageKey();
  return PAGE_TRANSLATIONS[pageKey]?.[lang]?.[key]
    ?? COMMON_TRANSLATIONS[lang]?.[key]
    ?? COMMON_TRANSLATIONS.en[key]
    ?? key;
}

