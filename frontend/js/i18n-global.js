function getCurrentLanguage() {
  const saved = localStorage.getItem(LANG_STORAGE_KEY);
  return saved === 'es' ? 'es' : 'en';
}

function getPageKey() {
  return document.body?.dataset?.page || '';
}

function applyTranslations() {
  const pageKey = getPageKey();
  const lang = getCurrentLanguage();
  const dict = PAGE_TRANSLATIONS[pageKey]?.[lang];

  if (!dict) {
    return;
  }

  document.documentElement.lang = lang;
  if (dict.pageTitle) {
    document.title = dict.pageTitle;
  }

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (dict[key]) {
      element.textContent = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (dict[key]) {
      element.placeholder = dict[key];
    }
  });

  document.querySelectorAll('.lang-btn[data-language]').forEach((button) => {
    const isActive = button.dataset.language === lang;
    button.classList.toggle('active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
    const textKey = button.dataset.language === 'en' ? 'english' : 'spanish';
    if (dict[textKey]) {
      button.textContent = dict[textKey];
    }
  });
}

function setupLanguageButtons() {
  document.querySelectorAll('.lang-btn[data-language]').forEach((button) => {
    button.addEventListener('click', () => {
      const next = button.dataset.language === 'es' ? 'es' : 'en';
      localStorage.setItem(LANG_STORAGE_KEY, next);
      applyTranslations();
      document.dispatchEvent(new CustomEvent('bellaveste:language-changed', { detail: { language: next } }));
    });
  });
}

document.addEventListener('DOMContentLoaded', () => {
  setupLanguageButtons();
  applyTranslations();
});
